function extractBestPhone(rawUser: Record<string, unknown>): string {
  if (typeof rawUser.phone === 'string' && rawUser.phone.trim()) {
    return rawUser.phone.trim();
  }
  const pending = rawUser.pendingPayment as Record<string, unknown> | undefined;
  if (pending && typeof pending.senderPhone === 'string' && pending.senderPhone.trim()) {
    return pending.senderPhone.trim();
  }
  if (Array.isArray(rawUser.paymentHistory)) {
    for (const ph of rawUser.paymentHistory) {
      const pObj = ph as Record<string, unknown>;
      if (pObj && typeof pObj.senderPhone === 'string' && pObj.senderPhone.trim()) {
        return pObj.senderPhone.trim();
      }
    }
  }
  return '';
}

function sanitizeLegacyUserForClient(
  rawObj: Record<string, unknown>,
  emailKey: string,
  uid: string
): Record<string, unknown> {
  const cleaned = { ...rawObj };
  delete cleaned.password;

  const firstMs =
    Number(cleaned.firstEntryAt) > 0
      ? Number(cleaned.firstEntryAt)
      : Number(cleaned.createdAt) > 0
      ? Number(cleaned.createdAt)
      : Date.now();

  cleaned.uid = uid;
  cleaned.email = emailKey;
  cleaned.firstEntryAt = firstMs;
  cleaned.createdAt = firstMs;
  cleaned.phone = extractBestPhone(cleaned);

  if (Array.isArray(cleaned.periods)) {
    cleaned.periods = cleaned.periods
      .filter((p) => {
        const rec = p as Record<string, unknown>;
        return rec && !rec.autoGenerated && typeof rec.startDate === 'string';
      })
      .map((p) => {
        const rec = p as Record<string, unknown>;
        return {
          startDate: rec.startDate,
          endDate: rec.endDate || null,
        };
      });
  }

  if (Array.isArray(cleaned.therapyLogs)) {
    cleaned.therapyLogs = cleaned.therapyLogs.filter((t) => {
      const rec = t as Record<string, unknown>;
      return rec && rec.id !== 't-sample-1';
    });
  }

  if (Array.isArray(cleaned.journalEntries)) {
    cleaned.journalEntries = cleaned.journalEntries.filter((j) => {
      const rec = j as Record<string, unknown>;
      return rec && rec.id !== 'j-sample-1' && rec.id !== 'j-sample-2';
    });
  }

  if (Array.isArray(cleaned.entryHistory)) {
    cleaned.entryHistory = cleaned.entryHistory.map((eh) => {
      const copy = { ...(eh as Record<string, unknown>) };
      delete copy.password;
      return copy;
    });
  }

  return cleaned;
}

function loadLegacyStore(): PersistentStore {
  const users: Record<string, Record<string, unknown>> = {};
  let deletedEmails: Record<string, number> = {};
  let adminCfg = { ...DEFAULT_ADMIN_CFG };

  for (const candidatePath of [TMP_STORE_PATH, PROJECT_STORE_PATH]) {
    try {
      if (fs.existsSync(candidatePath)) {
        const raw = fs.readFileSync(candidatePath, 'utf-8');
        const parsed = JSON.parse(raw);
        if (parsed.deletedEmails && typeof parsed.deletedEmails === 'object') {
          deletedEmails = { ...deletedEmails, ...parsed.deletedEmails };
        }
        if (parsed.users && typeof parsed.users === 'object') {
          for (const [k, v] of Object.entries(parsed.users)) {
            if (!v || typeof v !== 'object') continue;
            const rec = v as Record<string, unknown>;
            const emailKey = String(rec.email || k).trim().toLowerCase();
            if (!emailKey || deletedEmails[emailKey]) continue;
            const copy = { ...rec };
            delete copy.password;
            users[emailKey] = copy;
          }
        }
        if (parsed.adminConfig && typeof parsed.adminConfig === 'object') {
          adminCfg = {
            ...DEFAULT_ADMIN_CFG,
            ...parsed.adminConfig,
            ownerEmail: OWNER_ADMIN_EMAIL,
            additionalAdmins: Array.isArray(parsed.adminConfig.additionalAdmins)
              ? parsed.adminConfig.additionalAdmins
              : [],
          };
        }
      }
    } catch (err) {
      console.error(`Could not load legacy store from ${candidatePath}:`, err);
    }
  }

  return {
    users,
    deletedEmails,
    adminConfig: adminCfg,
  };
}

function saveLegacyStore(store: PersistentStore) {
  for (const [dir, file] of [
    [PROJECT_DATA_DIR, PROJECT_STORE_PATH],
    [TMP_DATA_DIR, TMP_STORE_PATH],
  ]) {
    try {
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      fs.writeFileSync(file, JSON.stringify(store, null, 2), 'utf-8');
    } catch (err) {
      console.error(`Could not save store to ${file}:`, err);
    }
  }
}

