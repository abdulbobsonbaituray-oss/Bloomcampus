interface VerifiedFirebaseCaller {
  uid: string;
  email: string;
  emailVerified: boolean;
  isAdmin: boolean;
}

async function verifyFirebaseCaller(
  req: express.Request
): Promise<VerifiedFirebaseCaller | null> {
  if (!firebaseWebApiKey) return null;
  const authHeader = String(req.headers.authorization || '').trim();
  const match = authHeader.match(/^Bearer\s+(.+)$/i);
  const idToken = match ? match[1].trim() : '';
  if (!idToken) return null;

  try {
    const resp = await fetch(
      `https://identitytoolkit.googleapis.com/v1/accounts:lookup?key=${encodeURIComponent(firebaseWebApiKey)}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ idToken }),
      }
    );
    if (!resp.ok) return null;
    const data = (await resp.json()) as {
      users?: Array<{
        localId?: string;
        email?: string;
        emailVerified?: boolean;
        providerUserInfo?: Array<{ providerId?: string }>;
      }>;
    };
    const fbUser = data?.users?.[0];
    if (!fbUser || !fbUser.localId || !fbUser.email) return null;
    const cleanEmail = fbUser.email.trim().toLowerCase();
    const isGoogleProvider = Array.isArray(fbUser.providerUserInfo)
      ? fbUser.providerUserInfo.some((p) => p.providerId === 'google.com')
      : false;
    const emailVerified = Boolean(fbUser.emailVerified || isGoogleProvider);
    if (!emailVerified) return null;
    return {
      uid: fbUser.localId,
      email: cleanEmail,
      emailVerified,
      isAdmin: cleanEmail === OWNER_ADMIN_EMAIL,
    };
  } catch {
    return null;
  }
}

